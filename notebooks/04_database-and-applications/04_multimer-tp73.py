# Monomer side = hero runs for which NA-MPNN specificity PPMs were computed
# (these are hero's own selected sequences, NOT the dimer's palindrome cores).
hero_spec_dir = DATA / "jobs" / "hero" / "specificities" / PROTEIN / "specificity"
dimer_spec_dir = DATA / "jobs" / DIMER_JOB / "specificities" / PROTEIN / "specificity"
spec_npz_dnas = {f.stem.split("_")[-2] for f in hero_spec_dir.glob(f"{PROTEIN}_*.npz")}

# Rank monomer DNAs by the product of percentile ranks of ipTM and dom_pLDDT,
# then keep only the top TOP_N_MONO.
mono_rank = (
    hero_runs[hero_runs["dna"].isin(spec_npz_dnas)]
    .groupby("dna")[["ipTM", "dom_pLDDT"]]
    .mean()
)
mono_rank["score"] = mono_rank["ipTM"].rank(pct=True) * mono_rank["dom_pLDDT"].rank(
    pct=True
)
mono_npz_dnas = set(
    mono_rank.sort_values("score", ascending=False).head(TOP_N_MONO).index
)
hero_subset = hero_runs[hero_runs["dna"].isin(mono_npz_dnas)].copy()

print(f"Protein: {PROTEIN} ({TF_NAME})")
print(f"Dimer runs: {len(dimer_runs)}")
print(f"Hero total runs: {len(hero_runs)}")
print(f"Monomer specificity DNAs available: {len(spec_npz_dnas)}")
print(
    f"Monomer DNAs kept (top {TOP_N_MONO} by ipTM×dom_pLDDT pct-rank): {len(mono_npz_dnas)}"
)

